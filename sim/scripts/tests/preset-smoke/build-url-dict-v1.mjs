// Builds sim/scripts/RD/url_codec_v1_data.js, the frozen data behind link format v1 (see
// url_codec.js). This was run once, when the format was introduced, and must not be run again:
// changing the data would break every link made with it. To improve on it, add a new format.
//
// Usage: node build-url-dict-v1.mjs <captured.json>
// where captured.json comes from capture-preset-options.mjs.
//
// The data holds:
//  - BASE_V1: a snapshot of the default preset, which links store their differences from.
//  - VIEW_FIELDS_V1: a snapshot of the fields that views hold.
//  - DICT_V1: a dictionary for deflate, made from the link payloads of the presets. Deflate can
//    refer back at most 32KB, and nearer references are cheaper, so the dictionary is
//    whole payloads (sorted by name) followed by the "key":value members that appear in more
//    than one preset, in increasing order of how many presets use them, then cut to 32KB.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { getPreset, getFieldsInView } from "../../RD/presets.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const dataFile = path.join(here, "../../RD/url_codec_v1_data.js");
const maxDictBytes = 32768;

const capturedFile = process.argv[2];
if (!capturedFile) {
  console.error("Usage: node build-url-dict-v1.mjs <captured.json>");
  process.exit(1);
}
if (
  fs.existsSync(dataFile) &&
  fs.readFileSync(dataFile, "utf8").includes("FROZEN")
) {
  console.error(
    dataFile + " is frozen, and existing links depend on it. Not overwriting.",
  );
  process.exit(1);
}

function writeData(base, viewFields, dict) {
  fs.writeFileSync(
    dataFile,
    `// url_codec_v1_data.js
//
// FROZEN: the data behind link format v1 (see url_codec.js). Links depend on every byte of
// this file, so it must never be edited. Generated by
// sim/scripts/tests/preset-smoke/build-url-dict-v1.mjs.

export const BASE_V1 = ${JSON.stringify(base)};

export const VIEW_FIELDS_V1 = ${JSON.stringify(viewFields)};

export const DICT_V1 = ${JSON.stringify(dict)};
`,
  );
}

const base = getPreset("default");
const viewFields = getFieldsInView();
// Write the base and view fields first, so that payloadV1 can use them.
writeData(base, viewFields, "");
const { payloadV1 } = await import(
  pathToFileURL(path.join(here, "../../RD/url_codec.js")).href +
    "?" +
    Date.now()
);

const captured = JSON.parse(fs.readFileSync(capturedFile, "utf8"));
const names = Object.keys(captured).sort();
const payloads = names.map((name) => payloadV1(captured[name]));

// Count the presets that use each "key":value member, including those inside views.
const counts = new Map();
for (const payload of payloads) {
  const members = new Set();
  const add = (obj) => {
    for (const [key, value] of Object.entries(obj)) {
      if (key == "v" && Array.isArray(value)) value.forEach(add);
      else members.add(JSON.stringify({ [key]: value }).slice(1, -1));
    }
  };
  add(JSON.parse(payload));
  members.forEach((m) => counts.set(m, (counts.get(m) ?? 0) + 1));
}
const common = [...counts.entries()]
  .filter(([, count]) => count > 1)
  .sort((a, b) => a[1] - b[1] || (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
  .map(([member]) => member)
  .join(",");

let dict = payloads.join("") + common;
// Cut from the front, to at most maxDictBytes of UTF-8.
const encoder = new TextEncoder();
let start = Math.max(0, dict.length - maxDictBytes);
while (encoder.encode(dict.slice(start)).length > maxDictBytes) start++;
dict = dict.slice(start);

writeData(base, viewFields, dict);
console.log(
  `Wrote ${dataFile}: ${names.length} presets, ${encoder.encode(dict).length} bytes of dictionary.`,
);
